"""Reproducible independent-sequence delayed-bit memory classification.

The target is the input bit from 'delay' steps earlier. Training and test
sequences are generated by separate seeded streams; the reservoir is reset
between sequences. No target labels enter the reservoir.
"""

from dataclasses import asdict, dataclass, field
import random

from .readout import LogisticReadout
from .reservoir import Reservoir, ReservoirConfig


@dataclass(frozen=True)
class ExperimentConfig:
    seed: int = 369
    train_sequences: int = 36
    test_sequences: int = 12
    sequence_length: int = 36
    burn_in: int = 6
    delay: int = 2
    epochs: int = 16
    learning_rate: float = 0.035
    reservoir: ReservoirConfig = field(default_factory=ReservoirConfig)

    def __post_init__(self) -> None:
        if self.train_sequences < 1 or self.test_sequences < 1:
            raise ValueError("train_sequences and test_sequences must be positive")
        if self.sequence_length < 2:
            raise ValueError("sequence_length must be at least two")
        if self.delay < 1 or self.burn_in < 0:
            raise ValueError("delay must be positive and burn_in nonnegative")
        if max(self.delay, self.burn_in) >= self.sequence_length:
            raise ValueError("sequence_length must exceed delay and burn_in")
        if self.epochs < 1 or self.learning_rate <= 0:
            raise ValueError("epochs and learning_rate must be positive")


def dataset(
    reservoir: Reservoir,
    *,
    sequence_count: int,
    sequence_length: int,
    burn_in: int,
    delay: int,
    seed: int,
) -> tuple[list[tuple[float, ...]], list[int]]:
    rng = random.Random(seed)
    features: list[tuple[float, ...]] = []
    targets: list[int] = []
    for _ in range(sequence_count):
        bits = [rng.randrange(2) for _ in range(sequence_length)]
        reservoir.reset()
        for t, bit in enumerate(bits):
            state = reservoir.step(float(bit))
            if t >= max(burn_in, delay):
                features.append(state)
                targets.append(bits[t - delay])
    return features, targets


def run_experiment(config: ExperimentConfig | None = None) -> dict:
    cfg = config or ExperimentConfig()
    reservoir = Reservoir(cfg.reservoir)
    train_x, train_y = dataset(
        reservoir, sequence_count=cfg.train_sequences,
        sequence_length=cfg.sequence_length, burn_in=cfg.burn_in,
        delay=cfg.delay, seed=cfg.seed + 101
    )
    test_x, test_y = dataset(
        reservoir, sequence_count=cfg.test_sequences,
        sequence_length=cfg.sequence_length, burn_in=cfg.burn_in,
        delay=cfg.delay, seed=cfg.seed + 202
    )
    majority_label = int(sum(train_y) * 2 >= len(train_y))
    baseline = sum(y == majority_label for y in test_y) / len(test_y)
    readout = LogisticReadout()
    readout.fit(train_x, train_y, epochs=cfg.epochs, learning_rate=cfg.learning_rate)
    return {
        "schema_version": "1.0",
        "project": "PhiNeuBio",
        "substrate": "software_simulation",
        "task": "delayed_binary_bit",
        "configuration": asdict(cfg),
        "samples": {"train": len(train_y), "test": len(test_y), "features": reservoir.feature_count},
        "metrics": {
            "training_accuracy": readout.score(train_x, train_y),
            "test_accuracy": readout.score(test_x, test_y),
            "majority_baseline_test_accuracy": baseline,
        },
        "limitations": [
            "This is a toy digital spiking-network task, not biological tissue.",
            "One seeded holdout is illustrative and does not establish generalization across tasks or seeds.",
            "Task classification performance does not indicate consciousness.",
        ],
    }
